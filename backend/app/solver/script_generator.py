"""Reproducible Python Simulation Script Generator from Validated Canonical Models.

Security Note:
- Only validated structured models (CanonicalSimulationModel -> NormalizedSIModel) are accepted.
- Numeric constants are formatted strictly as floats/ints; no user-provided code is ever executed.
"""

from __future__ import annotations

import json
from typing import Optional

from app.schemas.model_schema import (
    ALL_FACE_IDS,
    BoundaryConditionType,
    CanonicalSimulationModel,
)
from app.solver.unit_converter import convert_and_validate_si_model


def generate_reproducible_python_script(
    model: CanonicalSimulationModel,
    override_max_element_size: Optional[float] = None,
    override_polynomial_order: Optional[int] = None,
) -> str:
    """Generate a standalone, editable NGSolve Python script reproducing the exact 3D FEM simulation."""
    si = convert_and_validate_si_model(
        model,
        override_max_element_size=override_max_element_size,
        override_polynomial_order=override_polynomial_order,
    )

    dirichlet_dict: dict[str, float] = {}
    neumann_dict: dict[str, float] = {}
    robin_dict: dict[str, tuple[float, float]] = {}

    for face_id in ALL_FACE_IDS:
        bc = si.boundary_conditions[face_id]
        fname = face_id.value
        if bc.bc_type == BoundaryConditionType.DIRICHLET and bc.temperature_k is not None:
            dirichlet_dict[fname] = round(float(bc.temperature_k), 6)
        elif (
            bc.bc_type == BoundaryConditionType.NEUMANN
            and bc.outward_heat_flux_w_m2 is not None
        ):
            neumann_dict[fname] = round(float(bc.outward_heat_flux_w_m2), 6)
        elif (
            bc.bc_type == BoundaryConditionType.ROBIN
            and bc.convection_coeff_w_m2k is not None
            and bc.ambient_temperature_k is not None
        ):
            robin_dict[fname] = (
                round(float(bc.convection_coeff_w_m2k), 6),
                round(float(bc.ambient_temperature_k), 6),
            )

    safe_title = json.dumps(model.metadata.name)
    safe_material = json.dumps(model.material.name)

    script = f'''#!/usr/bin/env python3
"""
Reproducible 3D Steady-State Heat Conduction FEM Simulation
Generated by PDE Simulation Studio (Canonical Schema v{model.schema_version})

Project: {safe_title}
Material: {safe_material}
Governing Equation: -div(k * grad(T)) = Q  in Omega
"""

from __future__ import annotations

import json
import ngsolve as ngs
from netgen.occ import Axis, Box, OCCGeometry, Pnt, Vec

# ---------------------------------------------------------------------------
# 1. SI Model Parameters (Converted from input units: length='{si.length_unit.value}', temp='{si.temperature_unit.value}')
# ---------------------------------------------------------------------------
LX_M = {si.lx_m:.8g}
LY_M = {si.ly_m:.8g}
LZ_M = {si.lz_m:.8g}

POS_X_M = {si.pos_x_m:.8g}
POS_Y_M = {si.pos_y_m:.8g}
POS_Z_M = {si.pos_z_m:.8g}

ROT_X_DEG = {si.rot_x_deg:.8g}
ROT_Y_DEG = {si.rot_y_deg:.8g}
ROT_Z_DEG = {si.rot_z_deg:.8g}

MAX_ELEMENT_SIZE_M = {si.maxh_m:.8g}
POLYNOMIAL_ORDER = {int(si.polynomial_order)}

THERMAL_CONDUCTIVITY_K = {si.thermal_conductivity_w_mk:.8g}  # W/(m*K)
VOLUMETRIC_HEAT_SOURCE_Q = {si.volumetric_heat_source_w_m3:.8g}  # W/m^3

# Semantic Boundary Condition Dictionaries (SI Units: K, W/m^2, W/(m^2*K))
DIRICHLET_BC = {repr(dirichlet_dict)}
NEUMANN_OUTWARD_FLUX_BC = {repr(neumann_dict)}
ROBIN_CONVECTION_BC = {repr(robin_dict)}  # face_id: (h_W_m2K, T_ambient_K)


def build_geometry_and_mesh() -> ngs.Mesh:
    """Create 3D OpenCASCADE rectangular cuboid, tag semantic faces X_MIN..Z_MAX, and mesh."""
    box = Box(
        Pnt(-LX_M / 2.0, -LY_M / 2.0, -LZ_M / 2.0),
        Pnt(LX_M / 2.0, LY_M / 2.0, LZ_M / 2.0),
    )
    box.mat("solid_domain")

    tol = 1e-6 * min(LX_M, LY_M, LZ_M)
    for face in box.faces:
        c = face.center
        if abs(c.x - (-LX_M / 2.0)) <= tol:
            face.name = "X_MIN"
        elif abs(c.x - (LX_M / 2.0)) <= tol:
            face.name = "X_MAX"
        elif abs(c.y - (-LY_M / 2.0)) <= tol:
            face.name = "Y_MIN"
        elif abs(c.y - (LY_M / 2.0)) <= tol:
            face.name = "Y_MAX"
        elif abs(c.z - (-LZ_M / 2.0)) <= tol:
            face.name = "Z_MIN"
        elif abs(c.z - (LZ_M / 2.0)) <= tol:
            face.name = "Z_MAX"

    if abs(ROT_Z_DEG) > 1e-9:
        box = box.Rotate(Axis(Pnt(0, 0, 0), Vec(0, 0, 1)), ROT_Z_DEG)
    if abs(ROT_Y_DEG) > 1e-9:
        box = box.Rotate(Axis(Pnt(0, 0, 0), Vec(0, 1, 0)), ROT_Y_DEG)
    if abs(ROT_X_DEG) > 1e-9:
        box = box.Rotate(Axis(Pnt(0, 0, 0), Vec(1, 0, 0)), ROT_X_DEG)

    if abs(POS_X_M) > 1e-9 or abs(POS_Y_M) > 1e-9 or abs(POS_Z_M) > 1e-9:
        box = box.Move(Vec(POS_X_M, POS_Y_M, POS_Z_M))

    geo = OCCGeometry(box)
    ngmesh = geo.GenerateMesh(maxh=MAX_ELEMENT_SIZE_M)
    return ngs.Mesh(ngmesh)


def run_simulation() -> dict[str, object]:
    """Assemble and solve the steady-state heat conduction equation -div(k grad(T)) = Q."""
    mesh = build_geometry_and_mesh()
    dirichlet_regex = "|".join(DIRICHLET_BC.keys())

    fes = ngs.H1(mesh, order=POLYNOMIAL_ORDER, dirichlet=dirichlet_regex)
    u, v = fes.TrialFunction(), fes.TestFunction()

    # Bilinear Form: domain diffusion + Robin boundary terms
    a = ngs.BilinearForm(fes, symmetric=True)
    a += THERMAL_CONDUCTIVITY_K * ngs.grad(u) * ngs.grad(v) * ngs.dx
    for face_name, (h_val, _t_amb) in ROBIN_CONVECTION_BC.items():
        a += h_val * u * v * ngs.ds(face_name)

    # Linear Form: internal heat generation + Neumann outward flux + Robin ambient terms
    f = ngs.LinearForm(fes)
    if abs(VOLUMETRIC_HEAT_SOURCE_Q) > 0.0:
        f += VOLUMETRIC_HEAT_SOURCE_Q * v * ngs.dx
    for face_name, q_out in NEUMANN_OUTWARD_FLUX_BC.items():
        f += (-q_out) * v * ngs.ds(face_name)
    for face_name, (h_val, t_amb) in ROBIN_CONVECTION_BC.items():
        f += (h_val * t_amb) * v * ngs.ds(face_name)

    a.Assemble()
    f.Assemble()

    gfu = ngs.GridFunction(fes)
    if DIRICHLET_BC:
        cf_dirichlet = mesh.BoundaryCF(DIRICHLET_BC, default=0.0)
        gfu.Set(cf_dirichlet, definedon=mesh.Boundaries(dirichlet_regex))

    residual = f.vec.CreateVector()
    residual.data = f.vec - a.mat * gfu.vec
    gfu.vec.data += a.mat.Inverse(fes.FreeDofs(), inverse="sparsecholesky") * residual

    # Export VTK (.vtu) for ParaView visualization
    vtk = ngs.VTKOutput(
        mesh,
        coefs=[gfu, -THERMAL_CONDUCTIVITY_K * ngs.grad(gfu)],
        names=["Temperature_K", "HeatFlux_W_m2"],
        filename="solution",
        subdivision=0,
    )
    vtk.Do()
    del vtk

    vertex_temps = [float(gfu.vec[i]) for i in range(mesh.nv)]
    volume_m3 = float(ngs.Integrate(ngs.CF(1.0), mesh))
    mean_temp_k = float(ngs.Integrate(gfu, mesh)) / volume_m3

    summary = {{
        "mesh_vertices": mesh.nv,
        "mesh_tetrahedra": mesh.ne,
        "total_dofs": fes.ndof,
        "min_temperature_k": round(min(vertex_temps), 5),
        "max_temperature_k": round(max(vertex_temps), 5),
        "mean_temperature_k": round(mean_temp_k, 5),
    }}
    with open("results_summary.json", "w", encoding="utf-8") as fp:
        json.dump(summary, fp, indent=2)

    print("Simulation completed:", json.dumps(summary, indent=2))
    return summary


if __name__ == "__main__":
    run_simulation()
'''
    return script

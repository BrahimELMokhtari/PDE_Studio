"""Downloadable Simulation Project Packager (.zip archive builder)."""

from __future__ import annotations

import io
import zipfile
from typing import Optional

from app.schemas.model_schema import CanonicalSimulationModel
from app.schemas.simulation_schema import SimulationResultSummary
from app.solver.exporter import (
    export_boundary_csv_bytes,
    export_nodal_csv_bytes,
    export_surface_vtu_from_summary,
)
from app.solver.script_generator import generate_reproducible_python_script


def build_simulation_package_zip(
    model: CanonicalSimulationModel,
    result: Optional[SimulationResultSummary] = None,
    override_max_element_size: Optional[float] = None,
    override_polynomial_order: Optional[int] = None,
    vtu_bytes_override: Optional[bytes] = None,
) -> bytes:
    """Create a complete downloadable ZIP archive containing simulation.py, model.json, VTU/CSV results, dependencies, and instructions."""
    script_py = generate_reproducible_python_script(
        model,
        override_max_element_size=override_max_element_size,
        override_polynomial_order=override_polynomial_order,
    )
    model_json = model.model_dump_json(indent=2)

    requirements_txt = (
        "ngsolve>=6.2.2405\n"
        "netgen-mesher>=6.2.2405\n"
        "numpy>=1.26.0\n"
        "scipy>=1.12.0\n"
    )

    readme_md = f"""# {model.metadata.name} — Reproducible 3D FEM Simulation Package

Generated by **PDE Simulation Studio** (Canonical Schema `v{model.schema_version}`).

## Package Contents

- `simulation.py`: Standalone, editable Python script using **NGSolve** and **Netgen OpenCASCADE** (`netgen.occ`) to build the 3D cuboid, tag semantic boundaries (`X_MIN`..`Z_MAX`), generate the tetrahedral mesh, and solve `-div(k * grad(T)) = Q`.
- `model.json`: The exact validated canonical simulation model (`v1.0.0`) exported from the 3D studio.
- `requirements.txt`: Python dependencies required to run the simulation locally.
- `results_summary.json`: *(Included when exported from a completed simulation run)* Numerical FEM summary statistics, convergence diagnostics, boundary heat rates, and centerline temperature profiles.
- `solution.vtu`: *(Included when exported from a completed simulation run)* VTK XML UnstructuredGrid file compatible with ParaView and `vtk.js`.
- `nodal_results.csv`: *(Included when exported from a completed simulation run)* Nodal coordinates and temperature dataset.
- `boundary_summary.csv`: *(Included when exported from a completed simulation run)* Semantic boundary face temperatures and outward heat rates.

## How to Run Locally

1. Create and activate a Python 3.10+ virtual environment:
   ```bash
   python -m venv .venv
   # Windows PowerShell:
   .\\.venv\\Scripts\\Activate.ps1
   # Linux / macOS:
   source .venv/bin/activate
   ```
2. Install NGSolve and scientific dependencies:
   ```bash
   python -m pip install -r requirements.txt
   ```
3. Execute the finite element simulation script:
   ```bash
   python simulation.py
   ```
4. Inspect outputs:
   - `results_summary.json`: Nodal min/max/mean temperatures in Kelvin.
   - `solution.vtu`: 3D tetrahedral VTK mesh with `Temperature_K` and `HeatFlux_W_m2` fields ready for **ParaView**.
"""

    buffer = io.BytesIO()
    with zipfile.ZipFile(buffer, mode="w", compression=zipfile.ZIP_DEFLATED) as zf:
        zf.writestr("simulation.py", script_py)
        zf.writestr("model.json", model_json)
        zf.writestr("requirements.txt", requirements_txt)
        zf.writestr("README.md", readme_md)
        if result is not None:
            zf.writestr("results_summary.json", result.model_dump_json(indent=2))
            zf.writestr("nodal_results.csv", export_nodal_csv_bytes(result))
            zf.writestr("boundary_summary.csv", export_boundary_csv_bytes(result))
            vtu_data = (
                vtu_bytes_override
                if vtu_bytes_override is not None
                else export_surface_vtu_from_summary(result)
            )
            zf.writestr("solution.vtu", vtu_data)

    return buffer.getvalue()
